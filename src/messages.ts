export function fmt(msg: string, vars: Record<string, unknown>): string {
  return msg.replace(/\{(\w+)\}/g, (_, k: string) => {
    const v = vars[k]
    return typeof v === 'number' ? v.toLocaleString() : String(v ?? '')
  })
}
